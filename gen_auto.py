#!/usr/bin/env python3
"""Generate verified/part9_auto.py: a catalogue entry for every snapshotted repo that no hand/agent extraction covers.
These carry no claims (variants empty), only what the card and tags show mechanically."""
import json, glob, os, re

CODE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.environ.get("QCL_ROOT") or CODE          # data root: one folder per model (models/<slug>/); code stays here
idx = json.load(open(f"{ROOT}/snapshots/index.json"))["repos"]
covered = set()
for p in glob.glob(f"{ROOT}/verified/part*.py"):
    if p.endswith("part9_auto.py"): continue
    ns = {}; exec(open(p).read(), ns); covered |= {r["repo"] for r in ns["R"]}

MOD = re.compile(r"abliterat|uncensor|heretic|dealign|\bREAP|prun|finetun|fine-tun|distill|merge|cybersecurity|halogen|control-vector|lora", re.I)
from qcl_fmt import fmt_of

out = ["# AUTO-GENERATED by gen_auto.py — repos with no extracted claims. Do not edit by hand.", "R = []", "def repo(**k): R.append(k); return k", ""]
n = 0
for rid in sorted(set(idx) - covered):
    m = idx[rid]; tags = m.get("tags") or []
    txt = open(f"{ROOT}/{m['file']}", encoding="utf-8", errors="replace").read()
    flags = ["Not yet reviewed: card has not been read in full; it may contain quality claims"]
    if len(txt.strip()) < 50: flags = ["Card is empty or missing"]
    mod = bool(MOD.search(rid)) or any(MOD.search(t) for t in tags)
    out.append(f"repo(repo={rid!r}, sha={m['sha']!r}, fmt={fmt_of(rid, tags)!r}, runtime=None, weights_modified={mod}, method=None, methodology=None, variants=[], auto=True, flags={flags!r})")
    n += 1
open(f"{ROOT}/verified/part9_auto.py", "w").write("\n".join(out) + "\n")
print(f"auto-catalogued {n} repos; hand/agent-extracted {len(covered)}")
