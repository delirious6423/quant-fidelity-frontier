#!/usr/bin/env python3
"""Inventory of the task benchmarks that model cards report (machine-verified `bench:*` fields), grouped by canonical task.

  python3 pipeline/qcl_benchinv.py            # writes docs/reference/BENCHMARK_COVERAGE.md and prints a summary

Reads each live model's built site/data.json (values already copied verbatim from card text and gate-checked). Nothing is
typed here: names are grouped by rules, and anything the rules do not recognise is listed as 'unclassified' so a reader can
extend RULES. Sub-scores (a '/' in the name), error rates, speeds and counts are not task benchmarks and are left out."""
import collections, glob, json, os, re, subprocess, sys

CODE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(CODE, "web"))   # bench_tasks.py lives with the site generators
from bench_tasks import canonical

def main():
    live = subprocess.run([sys.executable, os.path.join(CODE, "pipeline", "qcl_live.py")], capture_output=True, text=True).stdout.split()
    tasks = collections.defaultdict(lambda: {"models": collections.defaultdict(lambda: {"repos": set(), "scores": 0, "sized": 0, "names": set()})})
    unclassified = collections.Counter()
    for root in live:
        slug = os.path.basename(root.rstrip("/")); path = os.path.join(CODE, root, "site", "data.json")
        if not os.path.exists(path): continue
        for r in json.load(open(path))["rows"]:
            for k, m in r["metrics"].items():
                if not k.startswith("bench:") or m.get("v") is None: continue
                task = canonical(k[6:])
                if task is None: continue
                if task == "unclassified": unclassified[k[6:]] += 1; continue
                e = tasks[task]["models"][slug]; e["repos"].add(r["repo"]); e["scores"] += 1; e["names"].add(k[6:]); e["sized"] += 1 if r.get("size_gb") else 0
    order = sorted(tasks, key=lambda t: (-len(tasks[t]["models"]), -sum(len(v["repos"]) for v in tasks[t]["models"].values()), t))
    out = ["# Benchmark coverage across model cards", "",
           "Generated by `pipeline/qcl_benchinv.py` from each live model's machine-verified `bench:*` fields (values copied verbatim from card text). "
           "It lists every task benchmark that cards report, not only the reviewed set shown on the Benchmarks page. 'Sized' counts scores whose build has a file size.", "",
           "| Benchmark | Models | Publishers (repos) | Scores | Sized | Raw names seen |", "| --- | ---: | ---: | ---: | ---: | --- |"]
    for t in order:
        ms = tasks[t]["models"]
        out.append(f"| {t} | {len(ms)} ({', '.join(sorted(ms))}) | {sum(len(v['repos']) for v in ms.values())} | {sum(v['scores'] for v in ms.values())} | "
                   f"{sum(v['sized'] for v in ms.values())} | {', '.join(sorted({n for v in ms.values() for n in v['names']})[:6])} |")
    out += ["", f"Unclassified names (extend RULES in the script to cover them): {len(unclassified)}", ""]
    out += [f"- {n} ({c})" for n, c in unclassified.most_common(60)]
    os.makedirs(os.path.join(CODE, "docs", "reference"), exist_ok=True)
    open(os.path.join(CODE, "docs", "reference", "BENCHMARK_COVERAGE.md"), "w").write("\n".join(out) + "\n")
    print(json.dumps({"tasks": len(tasks), "multi_model": sum(1 for t in tasks if len(tasks[t]["models"]) >= 2), "unclassified": len(unclassified)}))

if __name__ == "__main__": main()
