#!/usr/bin/env python3
"""Watchdog: what the hourly cycle has silently stopped doing. Read-only over the checkout; prints a report.

  python3 pipeline/qcl_watchdog.py                 # markdown report; exit 0
  python3 pipeline/qcl_watchdog.py --json          # the same as JSON
  python3 pipeline/qcl_watchdog.py --strict        # exit 1 when anything is overdue
  python3 pipeline/qcl_watchdog.py --issue         # open, update or close the one watchdog issue (gh, GH_TOKEN); exit 1 if gh fails

Two failure classes nothing else reports:
- Withdrawn values. A card that changes after review withdraws its reviewed claims (gates/current.py) until a fresh
  review covers it. The live cycle re-maps changed cards, but a mapping can bring back fewer values than the review it
  replaces (a hand review, an image transcription), and nothing restores image-only claims. Every repo whose reviewed
  entries hold more values (quality values and sizes, as the site counts them) than its current entries is listed; it
  is overdue once it has been seen withdrawn for longer than --grace-hours, so a card that changed this hour is left
  to the live-updates task first. The first time a repo is seen comes from the issue's saved state, so a later
  metadata refresh of the card cannot restart its grace period; without saved state the card's index time is used.
- Stalled tasks. Live updates: the newest logs/scan/*-live.jsonl must be younger than --max-cycle-hours (every run
  logs, idle or not). QA and publish: an idle QA run writes no log, so QA is judged by its job instead: main must not
  hold a publication change (deploy_state.publication_changes) newer than audit/deployed.json for longer than
  --max-unpublished-hours. That needs the history since the deployed commit (the workflow checks out without blobs)."""
import argparse, collections, datetime as dt, glob, hashlib, json, os, re, subprocess, sys

CODE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path[:0] = [os.path.join(CODE, "gates"), os.path.join(CODE, "pipeline")]
import current as CUR
import deploy_state

TITLE = "Watchdog: withdrawn values or stalled tasks"
AUTHOR = "app/github-actions"   # only the workflow's own issue is adopted; anyone can open issues on a public repo
DIGEST = "<!-- watchdog-digest:{} -->"
STATE = re.compile(r"<!-- watchdog-state:(\{.*?\}) -->", re.S)
MACHINE = ("part8_machine.py", "part9_auto.py")   # regenerated by the pipeline; part9 carries no values
MAX_BODY = 60000                                  # GitHub rejects issue bodies over 65,536 characters
MAX_ROWS = 40                                     # per model in the issue table; the rest are counted


def parse_time(value):
    if not isinstance(value, str) or not value: return None
    try: return dt.datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone(dt.timezone.utc)
    except ValueError: return None


def stamp(t): return t.strftime("%Y-%m-%dT%H:%MZ") if t else None


def hours_since(now, t): return round((now - t).total_seconds() / 3600, 1) if t else None


def values(entry):
    """Values an entry publishes, counted as gates/verify.py walks them: every metric of every variant, cross and
    ladder row and of the baselines, plus each row's size, bpw and memory figure."""
    n = 0
    for kind in ("variants", "cross", "ladder"):
        for e in entry.get(kind) or []:
            n += len(e.get("m") or {}) + sum(1 for k in ("size", "bpw", "mem") if e.get(k) is not None)
    for key in ("baseline", "baseline2"):
        if isinstance(entry.get(key), dict):
            n += len([k for k in entry[key] if k not in ("L", "L_extra", "src")])
    return n


def withdrawn(root, now, grace_hours, first_seen=None, model=None):
    """Repos of one model whose reviewed values are not (all) back: [{repo, reviewed, current, lost, parts, image, ...}]."""
    first_seen = first_seen or {}
    with open(os.path.join(root, "snapshots/index.json")) as f: idx = json.load(f)["repos"]
    reviewed, current, parts, image = collections.Counter(), collections.Counter(), collections.defaultdict(set), set()
    for entry in CUR.load_entries(root):
        if entry.get("auto") or entry["_part"] == "part9_auto.py": continue
        repo = entry["repo"]
        if repo not in idx: continue   # the repo left the catalogue: nothing to restore
        n = values(entry)
        if CUR.fresh(entry, idx):
            current[repo] += n
        else:
            reviewed[repo] += n; parts[repo].add(entry["_part"])
            if any(e.get("src") == "chart_image" for kind in ("variants", "cross", "ladder") for e in entry.get(kind) or []):
                image.add(repo)
    out = []
    for repo, n in reviewed.items():
        if n <= current[repo]: continue
        meta = idx[repo]
        since = (parse_time(first_seen.get(f"{model}/{repo}")) or parse_time(meta.get("fetched_at"))
                 or parse_time(meta.get("lastModified")))
        hours = hours_since(now, since)
        out.append({"repo": repo, "reviewed": n, "current": current[repo], "lost": n - current[repo],
                    "parts": sorted(parts[repo]), "image": repo in image,
                    "hand_reviewed": any(p not in MACHINE for p in parts[repo]),
                    "since": stamp(since), "hours": hours, "overdue": hours is None or hours > grace_hours})
    return sorted(out, key=lambda r: (-r["lost"], r["repo"]))


def git(*args):
    return subprocess.run(["git", *args], cwd=CODE, capture_output=True, text=True)


def live_task(now, max_hours, logs=None):
    """Live updates log every run (idle or not): the newest *-live.jsonl (named by its UTC start) must be recent."""
    stamps = []
    for path in glob.glob(os.path.join(logs or os.path.join(CODE, "logs", "scan"), "*-live.jsonl")):
        m = re.match(r"(\d{8}T\d{4})Z-", os.path.basename(path))
        if m: stamps.append(dt.datetime.strptime(m[1], "%Y%m%dT%H%M").replace(tzinfo=dt.timezone.utc))
    last = max(stamps) if stamps else None
    hours = hours_since(now, last)
    return {"task": "live updates (:03)", "detail": f"last log {stamp(last) or 'none'}", "hours": hours,
            "overdue": hours is None or hours > max_hours}


def qa_task(now, max_hours):
    """QA publishes main: the oldest publication change on main after the deployed commit must be recent. An idle QA
    run (nothing to publish) writes no log, so the age of its log says nothing."""
    name = "QA and publish (:55)"
    deployed = deploy_state.read_json(os.path.join(CODE, "audit", "deployed.json"))
    base = deployed.get("commit") if isinstance(deployed, dict) else None
    if not isinstance(base, str) or not deploy_state.SHA.fullmatch(base):
        return {"task": name, "detail": "audit/deployed.json names no commit", "hours": None, "overdue": True}
    # First-parent history with each merge diffed against main's previous tip: a change counts from when it reached
    # main (the merge), not from when its branch commit was written.
    log = git("log", "--first-parent", "--diff-merges=first-parent", "--reverse", "--format=%x01%H %cI", "--name-only", f"{base}..HEAD")
    if log.returncode:
        return {"task": name, "detail": f"cannot compare main with the deployed commit {base[:7]} (history missing?)",
                "hours": None, "overdue": True}
    for chunk in log.stdout.split("\x01")[1:]:
        head, *paths = chunk.strip().splitlines()
        if deploy_state.publication_changes([p for p in paths if p]):
            since = parse_time(head.split()[1]); hours = hours_since(now, since)
            return {"task": name, "detail": f"unpublished changes on main since {stamp(since)} (deployed {base[:7]})",
                    "hours": hours, "overdue": hours > max_hours}
    return {"task": name, "detail": f"main is published (deployed {base[:7]})", "hours": 0.0, "overdue": False}


def live_roots():
    p = subprocess.run([sys.executable, os.path.join(CODE, "pipeline/qcl_live.py")], cwd=CODE, capture_output=True, text=True, check=True)
    return p.stdout.split()


def report(now=None, grace_hours=6, max_cycle_hours=3, max_unpublished_hours=4, roots=None, logs=None, first_seen=None):
    now = now or dt.datetime.now(dt.timezone.utc)
    models = {}
    for root in roots if roots is not None else live_roots():
        model = os.path.basename(root.rstrip("/"))
        rows = withdrawn(os.path.join(CODE, root), now, grace_hours, first_seen, model)
        if rows: models[model] = rows
    tasks = {"live": live_task(now, max_cycle_hours, logs), "qa": qa_task(now, max_unpublished_hours)}
    overdue = [r for rows in models.values() for r in rows if r["overdue"]]
    return {"at": stamp(now), "grace_hours": grace_hours, "max_cycle_hours": max_cycle_hours,
            "max_unpublished_hours": max_unpublished_hours, "tasks": tasks, "withdrawn": models,
            "summary": {"stalled_tasks": [t["task"] for t in tasks.values() if t["overdue"]],
                        "overdue_repos": len(overdue), "overdue_values": sum(r["lost"] for r in overdue),
                        "pending_repos": sum(len(rows) for rows in models.values()) - len(overdue)}}


def problems(rep):
    """The stable part of a report: what is overdue, without ages (they change every hour)."""
    rows = sorted((m, r["repo"], r["lost"]) for m, rs in rep["withdrawn"].items() for r in rs if r["overdue"])
    return {"stalled": rep["summary"]["stalled_tasks"], "withdrawn": rows}


def state(rep, max_rows=None):
    """When each listed repo was first seen withdrawn; carried in the issue body so the grace period cannot restart.
    A body that must shrink keeps the rows its table shows (the largest losses)."""
    return {f"{m}/{r['repo']}": r["since"] for m, rows in rep["withdrawn"].items() for r in rows[:max_rows] if r["since"]}


def markdown(rep, max_rows=None):
    s = rep["summary"]
    out = [f"Watchdog at {rep['at']} (withdrawn values overdue after {rep['grace_hours']} h; live updates after "
           f"{rep['max_cycle_hours']} h without a log; QA after {rep['max_unpublished_hours']} h of unpublished changes)", "",
           "## Scheduled tasks"]
    for t in rep["tasks"].values():
        age = f", {t['hours']} h" if t["hours"] else ""
        out.append(f"- {t['task']}: {t['detail']}{age}: {'**stalled**' if t['overdue'] else 'ok'}")
    out += ["", "## Withdrawn values not restored"]
    if not rep["withdrawn"]:
        out.append("None: every reviewed value is current.")
    for model, rows in rep["withdrawn"].items():
        out += ["", f"### {model}", "", "| Repo | Reviewed | Now | Lost | Kind | Withdrawn since | State |", "|---|---|---|---|---|---|---|"]
        for r in rows[:max_rows]:
            kind = "chart images" if r["image"] else ("hand review" if r["hand_reviewed"] else "machine mapping")
            out.append(f"| [{r['repo']}](https://huggingface.co/{r['repo']}) | {r['reviewed']} | {r['current']} | {r['lost']} | {kind} "
                       f"| {r['since'] or 'unknown'} | {'**overdue**' if r['overdue'] else 'within grace'} |")
        if max_rows is not None and len(rows) > max_rows:
            out.append(f"| and {len(rows) - max_rows} more repos ({sum(r['lost'] for r in rows[max_rows:])} values): run `python3 pipeline/qcl_watchdog.py` | | | | | | |")
    out += ["", f"Overdue: {s['overdue_values']} values on {s['overdue_repos']} repos; within grace: {s['pending_repos']} repos; "
            f"stalled tasks: {', '.join(s['stalled_tasks']) or 'none'}.",
            "", "What to do: docs/runbooks/HOURLY.md, section \"Watchdog\"."]
    return "\n".join(out)


def issue_body(rep):
    for rows in (None, MAX_ROWS, 15, 5, 0):
        table = MAX_ROWS if rows is None else rows   # the full saved state first, then table and state shrink together
        body = (markdown(rep, table) + "\n\n" + DIGEST.format(digest(rep))
                + "\n<!-- watchdog-state:" + json.dumps(state(rep, rows), sort_keys=True) + " -->")
        if len(body) <= MAX_BODY: return body
    raise RuntimeError("watchdog issue body is too long even without rows")


def digest(rep): return hashlib.sha256(json.dumps(problems(rep), sort_keys=True).encode()).hexdigest()[:16]


class GhError(RuntimeError): pass


def gh(*args, input=None):
    p = subprocess.run(["gh", *args], cwd=CODE, capture_output=True, text=True, input=input)
    if p.returncode: raise GhError(f"gh {' '.join(args[:2])} failed: {(p.stderr or p.stdout).strip()[-300:]}")
    return p.stdout


def find_issue():
    """The workflow's own open watchdog issue, or None."""
    found = json.loads(gh("issue", "list", "--state", "open", "--author", AUTHOR, "--search", f'in:title "{TITLE}"',
                          "--json", "number,title,body", "--limit", "20") or "[]")
    return next((i for i in found if i["title"] == TITLE), None)


def saved_state(open_issue):
    m = STATE.search((open_issue or {}).get("body") or "")
    try: return json.loads(m[1]) if m else {}
    except ValueError: return {}


def issue(rep, open_issue):
    """One open issue while anything is overdue. Body = the current report; a comment only when the set of problems
    changes (watchers hear news, not every hour); closed with a comment when all is clear. Every gh failure raises."""
    probs = problems(rep)
    if not probs["stalled"] and not probs["withdrawn"]:
        if not open_issue: return "all clear; no issue open"
        gh("issue", "comment", str(open_issue["number"]), "--body", f"All clear at {rep['at']}: nothing withdrawn is overdue and every task ran.")
        gh("issue", "close", str(open_issue["number"]))
        return f"closed #{open_issue['number']}"
    body = issue_body(rep)
    if not open_issue:
        return "opened " + gh("issue", "create", "--title", TITLE, "--body-file", "-", input=body).strip()
    changed = DIGEST.format(digest(rep)) not in (open_issue.get("body") or "")
    gh("issue", "edit", str(open_issue["number"]), "--body-file", "-", input=body)
    if changed:
        s = rep["summary"]
        gh("issue", "comment", str(open_issue["number"]), "--body",
           f"Changed at {rep['at']}: {s['overdue_values']} values overdue on {s['overdue_repos']} repos; "
           f"stalled tasks: {', '.join(s['stalled_tasks']) or 'none'}.")
    return f"updated #{open_issue['number']}" + (" (new problems, commented)" if changed else "")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--strict", action="store_true")
    ap.add_argument("--issue", action="store_true")
    ap.add_argument("--grace-hours", type=float, default=6)
    ap.add_argument("--max-cycle-hours", type=float, default=3)
    ap.add_argument("--max-unpublished-hours", type=float, default=4)
    a = ap.parse_args()
    try:
        open_issue = find_issue() if a.issue else None
        rep = report(grace_hours=a.grace_hours, max_cycle_hours=a.max_cycle_hours,
                     max_unpublished_hours=a.max_unpublished_hours, first_seen=saved_state(open_issue))
        print(json.dumps(rep, indent=1) if a.json else markdown(rep))
        if a.issue: print(issue(rep, open_issue), file=sys.stderr)
    except GhError as error:
        print(f"FAIL {error}", file=sys.stderr); sys.exit(1)
    p = problems(rep)
    sys.exit(1 if a.strict and (p["stalled"] or p["withdrawn"]) else 0)
